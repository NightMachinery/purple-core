PlaylistInventoryResult ReconcilePlaylistInventory(
		const PlaylistInventoryInput &input) {
	if (!input.currentChat) {
		return InvalidInventory(PlaylistInventoryError::InvalidCurrentChat);
	}
	PlaylistLocalState currentCheck;
	currentCheck.chat = *input.currentChat;
	const auto currentValid = ValidatePlaylistLocalState(currentCheck, input.selfUserId);
	if (currentValid.status != PlaylistLocalStatus::Valid) {
		return InvalidInventory(
			(currentValid.error == PlaylistLocalError::InvalidSelfUserId)
				? PlaylistInventoryError::InvalidSelfUserId
				: PlaylistInventoryError::InvalidCurrentChat);
	}

	PlaylistLocalState priorCheck;
	priorCheck.chat = input.priorChat;
	priorCheck.memo = input.priorMemo;
	const auto priorValid = ValidatePlaylistLocalState(priorCheck, input.selfUserId);
	if (priorValid.status != PlaylistLocalStatus::Valid) {
		if (priorValid.error == PlaylistLocalError::InvalidSelfUserId) {
			return InvalidInventory(PlaylistInventoryError::InvalidSelfUserId);
		}
		if (priorValid.error == PlaylistLocalError::InvalidChat) {
			return InvalidInventory(PlaylistInventoryError::InvalidPriorChat);
		}
		if (priorValid.error == PlaylistLocalError::MissingField
				&& !input.priorChat.has_value()
				&& !input.priorMemo.empty()) {
			return InvalidInventory(PlaylistInventoryError::MissingPriorChat);
		}
		return InvalidInventory(PlaylistInventoryError::InvalidMemo);
	}

	const auto normCurrent = NormalizeBoundChat(*input.currentChat, input.selfUserId);
	const auto normPrior = input.priorChat
		? std::optional<PeerToken>(NormalizeBoundChat(*input.priorChat, input.selfUserId))
		: std::nullopt;
	const bool bindingChanged = normPrior.has_value() && (*normPrior != normCurrent);

	if (!input.listingSucceeded) {
		PlaylistInventoryResult result;
		result.status = PlaylistInventoryStatus::Valid;
		result.error = PlaylistInventoryError::None;
		result.bindingChanged = bindingChanged;
		result.normalizedCurrentChat = normCurrent;
		result.normalizedPriorChat = normPrior;
		result.metadataComplete = false;
		if (!bindingChanged) {
			result.unresolvedPriorMemo = input.priorMemo;
		}
		return result;
	}

	DedupedListed listed;
	for (const auto &obs : input.listedObservations) {
		if (const auto err = ValidateObservationInput(obs)) {
			return InvalidInventory(*err);
		}
		const auto id = int32_t(obs.messageId);
		if (listed.conflicts.contains(id)) {
			continue;
		}
		const auto it = listed.unique.find(id);
		if (it == listed.unique.end()) {
			listed.unique.emplace(id, obs);
		} else if (!SameObservationFact(it->second, obs)) {
			listed.unique.erase(it);
			listed.conflicts.insert(id);
		}
	}

	std::set<int32_t> requestedById;
	if (!bindingChanged) {
		for (const auto &[id, entry] : input.priorMemo) {
			if (!listed.unique.contains(id) && !listed.conflicts.contains(id)) {
				requestedById.insert(id);
			}
		}
	}

	DedupedById byId;
	if (!bindingChanged && input.byIdSucceeded) {
		for (const auto &row : input.byIdObservations) {
			if (!IsValidMessageId(row.messageId)) {
				return InvalidInventory(PlaylistInventoryError::InvalidMessageId);
			}
			if (!IsValidByIdOutcome(row.outcome)) {
				return InvalidInventory(PlaylistInventoryError::InvalidByIdOutcome);
			}
			const auto id = int32_t(row.messageId);
			if (!requestedById.contains(id)) {
				continue;
			}
			if (row.outcome == PlaylistByIdOutcome::Present
					&& row.documentId == 0
					&& RequiresNonZeroDocumentId(row.meta, row.ownership)) {
				return InvalidInventory(PlaylistInventoryError::InvalidDocumentId);
			}
			if (byId.conflicts.contains(id)) {
				continue;
			}
			const auto it = byId.unique.find(id);
			if (it == byId.unique.end()) {
				byId.unique.emplace(id, row);
			} else if (!SameByIdFact(it->second, row)) {
				byId.unique.erase(it);
				byId.conflicts.insert(id);
			}
		}
	}

	PlaylistInventoryResult result;
	result.status = PlaylistInventoryStatus::Valid;
	result.error = PlaylistInventoryError::None;
	result.bindingChanged = bindingChanged;
	result.normalizedCurrentChat = normCurrent;
	result.normalizedPriorChat = normPrior;

	const auto *activePriorMemo = bindingChanged ? nullptr : &input.priorMemo;
	std::set<int32_t> unknownSet;
	std::set<int32_t> conflictSet = listed.conflicts;

	if (activePriorMemo != nullptr) {
		for (const auto id : listed.conflicts) {
			const auto it = activePriorMemo->find(id);
			if (it != activePriorMemo->end()) {
				result.unresolvedPriorMemo.emplace(id, it->second);
			}
		}
	}

	for (const auto &[id, obs] : listed.unique) {
		ReconcilePresentObservation(
			id,
			obs.documentId,
			obs.ownership,
			obs.meta,
			false,
			activePriorMemo,
			result,
			unknownSet);
	}

	std::set<int32_t> pendingSet;
	std::set<int32_t> goneSet;
	for (const auto id : requestedById) {
		const auto priorIt = input.priorMemo.find(id);
		if (!input.byIdSucceeded) {
			pendingSet.insert(id);
			result.unresolvedPriorMemo.emplace(id, priorIt->second);
			continue;
		}
		if (byId.conflicts.contains(id)) {
			conflictSet.insert(id);
			result.unresolvedPriorMemo.emplace(id, priorIt->second);
			continue;
		}
		const auto it = byId.unique.find(id);
		if (it == byId.unique.end()) {
			pendingSet.insert(id);
			result.unresolvedPriorMemo.emplace(id, priorIt->second);
			continue;
		}
		const auto &row = it->second;
		switch (row.outcome) {
		case PlaylistByIdOutcome::Present:
			ReconcilePresentObservation(
				id,
				row.documentId,
				row.ownership,
				row.meta,
				true,
				activePriorMemo,
				result,
				unknownSet);
			break;
		case PlaylistByIdOutcome::Gone:
			goneSet.insert(id);
			break;
		case PlaylistByIdOutcome::Failed:
		case PlaylistByIdOutcome::Inaccessible:
		case PlaylistByIdOutcome::Cancelled:
			pendingSet.insert(id);
			result.unresolvedPriorMemo.emplace(id, priorIt->second);
			break;
		}
	}

	// Keep output vectors sorted ascending by messageId regardless of listing vs by-id origin.
	const auto sortByMessageId = [](auto &vec) {
		std::sort(vec.begin(), vec.end(), [](const auto &a, const auto &b) {
			return a.messageId < b.messageId;
		});
	};
	sortByMessageId(result.presentCandidates);
	sortByMessageId(result.readCandidates);
	sortByMessageId(result.reusableMemo);
	sortByMessageId(result.invalidatedMemo);

	result.confirmedGoneIds.assign(goneSet.begin(), goneSet.end());
	result.vanishedMemoRecordCount = result.confirmedGoneIds.size();
	result.pendingByIdIds.assign(pendingSet.begin(), pendingSet.end());
	result.unknownOwnershipIds.assign(unknownSet.begin(), unknownSet.end());
	result.conflictingIds.assign(conflictSet.begin(), conflictSet.end());

	result.metadataComplete = input.listingExhausted
		&& result.pendingByIdIds.empty()
		&& result.unknownOwnershipIds.empty()
		&& result.conflictingIds.empty();

	return result;
}

