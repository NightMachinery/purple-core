inline constexpr int64_t kMaximumInventoryMessageId =
	std::numeric_limits<int32_t>::max();

[[nodiscard]] PlaylistInventoryResult InvalidInventory(
		PlaylistInventoryError error) {
	PlaylistInventoryResult result;
	result.status = PlaylistInventoryStatus::InvalidInput;
	result.error = error;
	return result;
}

[[nodiscard]] bool IsValidMessageId(int64_t messageId) {
	return messageId > 0 && messageId <= kMaximumInventoryMessageId;
}

[[nodiscard]] bool IsValidByIdOutcome(PlaylistByIdOutcome outcome) {
	switch (outcome) {
	case PlaylistByIdOutcome::Present:
	case PlaylistByIdOutcome::Gone:
	case PlaylistByIdOutcome::Failed:
	case PlaylistByIdOutcome::Inaccessible:
	case PlaylistByIdOutcome::Cancelled:
		return true;
	}
	return false;
}

[[nodiscard]] bool RequiresNonZeroDocumentId(
		const PlaylistRecordMessageMeta &meta,
		SyncChatMessageOwnership ownership) {
	const auto verdict = InspectPlaylistRecordMetadata(meta, ownership);
	return verdict == PlaylistRecordCandidateVerdict::Candidate
		|| verdict == PlaylistRecordCandidateVerdict::UnknownOwnership;
}

[[nodiscard]] PeerToken NormalizeBoundChat(
		const PeerToken &token,
		uint64_t selfUserId) {
	if (token.kind == PeerTokenKind::User
			&& selfUserId > 0
			&& token.id == selfUserId) {
		return PeerToken{ PeerTokenKind::Self, 0 };
	}
	return token;
}

[[nodiscard]] bool SameObservationFact(
		const PlaylistInventoryObservation &a,
		const PlaylistInventoryObservation &b) {
	return a.documentId == b.documentId
		&& a.ownership == b.ownership
		&& a.meta == b.meta;
}

[[nodiscard]] bool SameByIdFact(
		const PlaylistByIdObservation &a,
		const PlaylistByIdObservation &b) {
	if (a.outcome != b.outcome) {
		return false;
	}
	if (a.outcome != PlaylistByIdOutcome::Present) {
		return true;
	}
	return a.documentId == b.documentId
		&& a.ownership == b.ownership
		&& a.meta == b.meta;
}

struct DedupedListed {
	std::map<int32_t, PlaylistInventoryObservation> unique;
	std::set<int32_t> conflicts;
};

struct DedupedById {
	std::map<int32_t, PlaylistByIdObservation> unique;
	std::set<int32_t> conflicts;
};

[[nodiscard]] std::optional<PlaylistInventoryError> ValidateObservationInput(
		const PlaylistInventoryObservation &obs) {
	if (!IsValidMessageId(obs.messageId)) {
		return PlaylistInventoryError::InvalidMessageId;
	}
	if (obs.documentId == 0 && RequiresNonZeroDocumentId(obs.meta, obs.ownership)) {
		return PlaylistInventoryError::InvalidDocumentId;
	}
	return std::nullopt;
}

void ReconcilePresentObservation(
		int32_t messageId,
		uint64_t documentId,
		SyncChatMessageOwnership ownership,
		const PlaylistRecordMessageMeta &meta,
		bool fromById,
		const std::map<int32_t, PlaylistLocalMemoEntry> *priorMemo,
		PlaylistInventoryResult &result,
		std::set<int32_t> &unknownSet) {
	const auto verdict = InspectPlaylistRecordMetadata(meta, ownership);
	const auto priorIt = priorMemo ? priorMemo->find(messageId) : std::map<int32_t, PlaylistLocalMemoEntry>::const_iterator();
	const bool hasPrior = (priorMemo != nullptr) && (priorIt != priorMemo->end());

	switch (verdict) {
	case PlaylistRecordCandidateVerdict::Candidate:
		result.presentCandidates.push_back(PlaylistInventoryPresentCandidate{
			.messageId = messageId,
			.documentId = documentId,
			.meta = meta,
			.fromById = fromById,
		});
		if (!hasPrior) {
			result.readCandidates.push_back(PlaylistInventoryReadCandidate{
				.messageId = messageId,
				.documentId = documentId,
				.meta = meta,
				.fromById = fromById,
			});
			return;
		}
		if (priorIt->second.documentId != documentId) {
			result.invalidatedMemo.push_back(PlaylistInventoryInvalidatedMemo{
				.messageId = messageId,
				.priorDocumentId = priorIt->second.documentId,
				.reason = PlaylistInventoryInvalidationReason::DocumentReplaced,
				.fromById = fromById,
			});
			result.readCandidates.push_back(PlaylistInventoryReadCandidate{
				.messageId = messageId,
				.documentId = documentId,
				.meta = meta,
				.fromById = fromById,
			});
			return;
		}
		// WHY: Valid memo hashes depend only on canonical bytes and may always
		// be skipped when (messageId, documentId) match; non-valid entries are
		// re-read if generated by a different classifier version.
		if (priorIt->second.state == PlaylistLocalMemoState::Valid
				|| priorIt->second.classifier == kPlaylistRecordClassifierVersion) {
			result.reusableMemo.push_back(PlaylistInventoryReusableEntry{
				.messageId = messageId,
				.entry = priorIt->second,
				.fromById = fromById,
			});
			return;
		}
		result.invalidatedMemo.push_back(PlaylistInventoryInvalidatedMemo{
			.messageId = messageId,
			.priorDocumentId = priorIt->second.documentId,
			.reason = PlaylistInventoryInvalidationReason::ClassifierUpgradeNeeded,
			.fromById = fromById,
		});
		result.readCandidates.push_back(PlaylistInventoryReadCandidate{
			.messageId = messageId,
			.documentId = documentId,
			.meta = meta,
			.fromById = fromById,
		});
		return;
	case PlaylistRecordCandidateVerdict::UnknownOwnership:
		unknownSet.insert(messageId);
		if (hasPrior) {
			result.unresolvedPriorMemo.emplace(messageId, priorIt->second);
		}
		return;
	case PlaylistRecordCandidateVerdict::AmbiguousSettings:
	case PlaylistRecordCandidateVerdict::Ignored:
		if (hasPrior) {
			result.invalidatedMemo.push_back(PlaylistInventoryInvalidatedMemo{
				.messageId = messageId,
				.priorDocumentId = priorIt->second.documentId,
				.reason = PlaylistInventoryInvalidationReason::LostEligibility,
				.fromById = fromById,
			});
		}
		return;
	}
}

